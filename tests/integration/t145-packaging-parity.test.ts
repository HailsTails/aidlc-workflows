// t145-packaging-parity: the package determinism and clean-build guard.
//
// covers: file:scripts/package.ts, file:src/hosts/codex/projection/settings-renderer.ts
//
// WHAT. The one-core-N-harnesses layout makes dist/ a GENERATED artifact: `bun
// scripts/package.ts` projects the harness-neutral core/ tree + harness/<name>/
// surfaces into ignored local dist/ and dist-release/ roots. `package.ts --check`
// builds all selected projections twice in independent temp roots and
// byte-compares those builds.
//
// This test IS that guard, run from the suite: it asserts `package.ts --check`
// exits 0 from source alone and rejects an intentionally nondeterministic
// emitter. Existing local generated bytes are never inputs to the check.
//
// WHY A SUBPROCESS. package.ts is a CLI that spawns the in-tree generators
// (aidlc-graph compile, aidlc-runner-gen) per harness; running it as a child
// mirrors how a developer or CI invokes it, and isolates its temp-dir builds
// from the suite's process.

import {
  NATIVE_MULTI_WORKTREE_CASE_TIMEOUT_MS,
  NATIVE_FIXTURE_SETUP_TIMEOUT_MS,
  remainingOperationTimeoutMs,
} from "../harness/test-budget.ts";
import { describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const PACKAGE_TS = join(REPO_ROOT, "scripts", "package.ts");
const CHECK_TIMEOUT_MS = NATIVE_MULTI_WORKTREE_CASE_TIMEOUT_MS;

type Run = ReturnType<typeof spawnSync>;

function copyDir(src: string, dst: string): void {
  cpSync(src, dst, { recursive: true });
}

function makeFixture(): string {
  const root = mkdtempSync(join(tmpdir(), "aidlc-package-contract-"));
  copyDir(join(REPO_ROOT, "core"), join(root, "core"));
  copyDir(join(REPO_ROOT, "scripts"), join(root, "scripts"));
  copyDir(join(REPO_ROOT, "src"), join(root, "src"));
  cpSync(join(REPO_ROOT, "package.json"), join(root, "package.json"));
  cpSync(join(REPO_ROOT, "bun.lock"), join(root, "bun.lock"));
  copyDir(join(REPO_ROOT, "harness"), join(root, "harness"));
  // Emitter imports (notably smol-toml) resolve from the checkout, not from
  // Bun's mutable global package cache.
  const nodeModules = join(REPO_ROOT, "node_modules");
  if (existsSync(nodeModules)) {
    symlinkSync(
      nodeModules,
      join(root, "node_modules"),
      process.platform === "win32" ? "junction" : "dir",
    );
  } else {
    const cache = spawnSync(process.execPath, ["pm", "cache"], {
      encoding: "utf-8",
    });
    const cacheRoot = (cache.stdout ?? "").trim();
    const packageJson = JSON.parse(
      readFileSync(join(REPO_ROOT, "package.json"), "utf-8"),
    ) as { devDependencies?: Record<string, string> };
    const version = packageJson.devDependencies?.["smol-toml"];
    const cached =
      cache.status === 0 && version
        ? readdirSync(cacheRoot).find((name) =>
            name.startsWith(`smol-toml@${version}`),
          )
        : undefined;
    if (!cached) throw new Error("smol-toml is unavailable in Bun's package cache");
    copyDir(
      join(cacheRoot, cached),
      join(root, "node_modules", "smol-toml"),
    );
  }
  return root;
}

function runPackage(root: string, ...args: string[]): Run {
  return spawnSync("bun", [join(root, "scripts", "package.ts"), ...args], {
    cwd: root,
    encoding: "utf-8",
    timeout: remainingOperationTimeoutMs(NATIVE_FIXTURE_SETUP_TIMEOUT_MS),
  });
}

function output(run: Run): string {
  return `${run.stdout ?? ""}${run.stderr ?? ""}`;
}

describe("t145 package determinism — two source-only builds match", () => {
  test("scripts/package.ts exists (the build entry)", () => {
    expect(existsSync(PACKAGE_TS)).toBe(true);
  });

  test("package.ts --check exits 0 for two independent complete builds", () => {
    const res = spawnSync("bun", [PACKAGE_TS, "--check"], {
      cwd: REPO_ROOT,
      encoding: "utf-8",
      timeout: remainingOperationTimeoutMs(NATIVE_FIXTURE_SETUP_TIMEOUT_MS),
    });
    if (res.status !== 0) {
      console.error(`package --check output:\n${res.stdout ?? ""}${res.stderr ?? ""}`);
    }
    expect(res.status).toBe(0);
  }, CHECK_TIMEOUT_MS);

  test("package.ts claude --check is clean without reading local projections", () => {
    const res = spawnSync("bun", [PACKAGE_TS, "claude", "--check"], {
      cwd: REPO_ROOT,
      encoding: "utf-8",
      timeout: remainingOperationTimeoutMs(NATIVE_FIXTURE_SETUP_TIMEOUT_MS),
    });
    if (res.status !== 0) {
      console.error(`package claude --check output:\n${res.stdout ?? ""}${res.stderr ?? ""}`);
    }
    expect(res.status).toBe(0);
    expect(res.stdout).toContain(
      "package --check: deterministic across two independent build(s) for claude.",
    );
  }, CHECK_TIMEOUT_MS);

  test("generated distribution roots are ignored developer outputs", () => {
    const ignored = spawnSync(
      "git",
      ["check-ignore", "dist/claude/.claude", "dist-release/claude/.claude"],
      { cwd: REPO_ROOT, encoding: "utf-8" },
    );
    expect(ignored.status).toBe(0);
    expect(ignored.stdout).toContain("dist/claude/.claude");
    expect(ignored.stdout).toContain("dist-release/claude/.claude");
  });
});

describe("t145 packager contract regressions", () => {
  test("an explicitly named harness without a manifest exits nonzero", () => {
    const root = makeFixture();
    try {
      const run = runPackage(root, "does-not-exist");
      expect(run.status).not.toBe(0);
      expect(output(run)).toContain('unknown harness "does-not-exist"');
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, CHECK_TIMEOUT_MS);

  test("--check works from a fixture with no generated roots and remains temp-only", () => {
    const root = makeFixture();
    try {
      const run = runPackage(root, "claude", "--check");
      expect(run.status, output(run)).toBe(0);
      expect(existsSync(join(root, "dist"))).toBe(false);
      expect(existsSync(join(root, "dist-release"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, CHECK_TIMEOUT_MS);

  test("--check reports the path built nondeterministically", () => {
    const root = makeFixture();
    try {
      const renderer = join(root, "src", "hosts", "claude", "projection", "settings-renderer.ts");
      const source = readFileSync(renderer, "utf-8");
      const stable = "allow: expanded } }, null, 2)";
      expect(source.split(stable)).toHaveLength(2);
      writeFileSync(renderer, source.replace(stable, "allow: expanded }, nonce: Math.random() }, null, 2)"));
      const run = runPackage(root, "claude", "--check");
      expect(run.status).not.toBe(0);
      expect(output(run).replaceAll("\\", "/")).toContain(
        "DIFFERS between builds: dist/claude/.claude/settings.json",
      );
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, CHECK_TIMEOUT_MS);

  test("--check ignores corrupted local generated bytes", () => {
    const root = makeFixture();
    try {
      const copyJunk = join(root, "dist", "claude", "local-only.txt");
      const releaseJunk = join(root, "dist-release", "claude", "local-only.txt");
      mkdirSync(dirname(copyJunk), { recursive: true });
      mkdirSync(dirname(releaseJunk), { recursive: true });
      writeFileSync(copyJunk, "corrupt copy output\n");
      writeFileSync(releaseJunk, "corrupt release output\n");
      const run = runPackage(root, "claude", "--check");
      expect(run.status, output(run)).toBe(0);
      expect(readFileSync(copyJunk, "utf-8")).toBe("corrupt copy output\n");
      expect(readFileSync(releaseJunk, "utf-8")).toBe("corrupt release output\n");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, CHECK_TIMEOUT_MS);

  test("full write removes generated harness and plugin roots absent from source", () => {
    const root = makeFixture();
    try {
      const staleHarness = join(root, "dist", "removed-harness", "stale.txt");
      const staleReleaseHarness = join(
        root,
        "dist-release",
        "removed-harness",
        "stale.txt",
      );
      const stalePlugin = join(
        root,
        "dist",
        "plugins",
        "removed-plugin",
        "claude",
        "stale.txt",
      );
      for (const path of [staleHarness, staleReleaseHarness, stalePlugin]) {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, "stale\n");
      }

      const run = runPackage(root);
      expect(run.status, output(run)).toBe(0);
      expect(existsSync(join(root, "dist", "removed-harness"))).toBe(false);
      expect(existsSync(join(root, "dist-release", "removed-harness"))).toBe(false);
      expect(existsSync(join(root, "dist", "plugins", "removed-plugin"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, CHECK_TIMEOUT_MS);

  test("write mode replaces only the named generated root", () => {
    const root = makeFixture();
    try {
      const stale = join(root, "dist", "kiro", "removed-root-output.txt");
      const pluginAsset = join(root, "dist", "plugins", "fixture", "keep.txt");
      const unrelatedAsset = join(root, "dist", "unrelated-root-asset.txt");
      mkdirSync(dirname(stale), { recursive: true });
      writeFileSync(stale, "stale\n");
      mkdirSync(dirname(pluginAsset), { recursive: true });
      writeFileSync(pluginAsset, "keep plugin\n");
      writeFileSync(unrelatedAsset, "keep root\n");

      const run = runPackage(root, "kiro");
      expect(run.status).toBe(0);
      expect(existsSync(stale)).toBe(false);
      expect(readFileSync(pluginAsset, "utf-8")).toBe("keep plugin\n");
      expect(readFileSync(unrelatedAsset, "utf-8")).toBe("keep root\n");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, CHECK_TIMEOUT_MS);
});
